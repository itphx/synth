/**
 * Помощники встраивания многострочного Markdown в текст промпта
 * (PROP-054, дополнение 2026-11-07).
 *
 * Проблема: значение с переводами строк (описание пункта плана, текст ToDo,
 * запись журнала), вставленное в список «- …», **разрывает** список: строки
 * после первой становятся отдельными абзацами, а заголовки/пункты внутри
 * значения — элементами внешнего списка.
 *
 * Решение — **отступ продолжения**: каждая строка значения, кроме первой,
 * получает отступ, выравнивающий её по содержимому внешнего пункта. Списки и
 * заголовки внутри значения остаются **внутри** пункта.
 */

/**
 * Отступ продолжения для содержимого пункта списка с маркером `- `.
 *
 * @param text многострочное значение
 * @param indent отступ для строк после первой (выравнивание по содержимому)
 */
export function indentContinuation(text: string, indent: string): string {
  if (!text) return '';
  return text.replace(/\r\n/g, '\n').replace(/\n/g, `\n${indent}`);
}

/**
 * Встроить многострочное значение в строку списка: первая строка — в строку
 * маркера, остальные — с отступом продолжения.
 */
export function embedMultiline(prefix: string, text: string, indent: string): string {
  const normalized = text.replace(/\r\n/g, '\n');
  const [first, ...rest] = normalized.split('\n');
  if (rest.length === 0) return `${prefix}${first}`;
  return `${prefix}${first}${indentContinuation(rest.join('\n'), indent)}`;
}
