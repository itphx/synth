/**
 * Обработчик classify-intent (AD-035).
 * Обогащает результат модели: нормализует лейбл, добавляет описание,
 * генерирует осмысленный ответ (аналог enum-decision).
 */
import type { MicroResult } from '../types.js';

/** Человекочитаемые описания интентов. */
const INTENT_DESCRIPTIONS: Record<string, string> = {
  question: 'Вопрос: пользователь хочет что-то узнать или понять.',
  command: 'Команда: пользователь хочет выполнить действие (написать, создать, исправить).',
  review: 'Ревью: пользователь хочет проверить или проанализировать что-то.',
  explain: 'Объяснение: пользователь хочет получить пояснение.',
  debug: 'Отладка: пользователь столкнулся с ошибкой или багом.',
  fix: 'Исправление: пользователь хочет что-то исправить.',
  test: 'Тестирование: пользователь хочет написать или запустить тесты.',
};

/** Готовые ответы для валидных интентов (аналог enum-decision). */
const CLASSIFY_ANSWERS: Record<string, string[]> = {
  question: ['Хороший вопрос. Для точного ответа мне нужно больше контекста — уточните, что именно интересует?'],
  command: ['Принято. Какая задача конкретно? Опишите, что нужно сделать.'],
  review: ['Понял, нужно провести ревью. Покажите фрагмент кода, и я оценю его качество.'],
  explain: ['Понял, нужно объяснение. О каком фрагменте/концепции речь?'],
  debug: ['Похоже на задачу отладки. Опишите ошибку или приложите лог — разберёмся.'],
  fix: ['Понял, нужно исправить ошибку. Покажите проблемный код — найдём причину.'],
  test: ['Понял, нужны тесты. Укажите функцию или модуль — напишу тесты.'],
};

export function handleClassifyIntent(modelResult: MicroResult): MicroResult {
  const label = modelResult.label || 'unknown';
  const description = INTENT_DESCRIPTIONS[label] ?? `Неизвестный интент: ${label}`;

  // Добавляем описание в signals для роутера (может влиять на выбор модели)
  const enrichedSignals = [...modelResult.signals, `intent:${label}`, `desc:${description}`];

  // Генерируем осмысленный ответ: интент распознан, но для полноценного
  // ответа нужен контекст (код, конкретика) — подтверждение + запрос деталей.
  const choices = CLASSIFY_ANSWERS[label] ?? [`Интент: ${label}`];
  const answer = choices[Math.floor(Math.random() * choices.length)]!;

  return {
    ...modelResult,
    answer,
    signals: enrichedSignals,
  };
}
