/**
 * ADR-089/ADR-052: контекст машинной аутентификации по API-ключу привязки.
 *
 * Единая точка расширения для будущей публичной API-платформы (ADR-052):
 * скоупы (`scopes`), идентичность отправителя (`principalId`) и источник
 * (`source`) появятся без смены сигнатур резолвера/журнала. Секрет ключа здесь
 * не хранится — только стабильные идентификаторы.
 */
export interface EventKeyCredential {
  keyId: string;
  bindingId: string;
  /**
   * Лимит запросов/мин конкретного ключа (ADR-089/ADR-052), если задан. Не задан —
   * применяется глобальный дефолт `events.keyRateLimitPerMinute`.
   */
  rateLimitPerMinute?: number;
  /** Источник из привязки (резолвится вызывающим). */
  source?: string;
  /**
   * ADR-089: владелец ключа привязки (его создатель) — атрибуция сессий,
   * материализуемых событием по machine-auth (`ephemeral`/`bind`). Иначе такие
   * сессии не имеют владельца и выпадают из `listSessions({ userId })`.
   */
  ownerId?: string;
  /** Задел ADR-052: скоупы ключа. */
  scopes?: string[];
  /** Задел ADR-052/ADR-089: идентичность отправителя. */
  principalId?: string;
}
