import { create } from 'zustand'

/**
 * Сигнал «каталог профилей исполнения изменился» (событие шины
 * `execution.updated`, инстансный канал).
 *
 * ## Зачем стор, если каталог читают компоненты
 *
 * Каталог профилей (`GET /execution/profiles`) нужен **не одному** месту:
 * разделу «Исполнение» (админ-настройки), селекту профиля агента
 * (`AgentsPanel`), профилю проекта (`ProjectTab`) и профилю сессии
 * (`SessionSettingsTab`). Каждый держит собственное состояние загрузки, ошибки
 * и черновика формы (у панелей свой разбор `503`/`501`/`403` в локализованный
 * текст), поэтому общим имеет смысл держать только **сигнал об изменении**:
 * счётчик `revision`, растущий на каждое серверное событие. Потребитель
 * перечитывает каталог своим обычным запросом, когда `revision` изменился
 * (первый рендер не дублируется — сравнивается со своим запомненным значением).
 *
 * Дубль каталога (свой `profiles` + `fetch` в сторе) здесь **не** заводится: он
 * разошёлся бы с локальными состояниями панелей и дал бы лишний `GET` на каждое
 * событие.
 *
 * Без инвалидации каталог «залипает»: профиль, созданный или переименованный в
 * разделе «Исполнение», не появляется в выпадающих списках до перезагрузки
 * страницы. Механический гейт — `event-invalidation-census.test.ts`.
 *
 * Guard-кэшей (`*Loaded`/`loadedProjects`) у стора нет намеренно: читать ли
 * каталог, решает каждый потребитель (например, `ProjectTab` не читает его без
 * права управления проектом).
 */
interface ExecutionProfilesStore {
  /**
   * Счётчик изменений каталога профилей исполнения.
   *
   * Растёт на каждое серверное событие `execution.updated`; по нему раздел
   * «Исполнение» (каталог + пулы) и селекторы профиля агента/проекта/сессии
   * перечитывают каталог без перезагрузки страницы.
   */
  revision: number
  /**
   * Каталог профилей изменился на сервере (профиль сохранён/удалён,
   * runtime-каталог сброшен к config, пул слит/удалён): поднять `revision`.
   *
   * Payload события (`{action, profileId?, poolName?}`) сигналу не нужен:
   * клиент перечитывает каталог целиком обычным запросом.
   */
  applyEvent: () => void
}

export const useExecutionProfilesStore = create<ExecutionProfilesStore>((set) => ({
  revision: 0,

  applyEvent: () => {
    set((s) => ({ revision: s.revision + 1 }))
  },
}))
