import { create } from 'zustand'

/**
 * Счётчик изменений идентичностей пользователя (событие шины
 * `identities.updated`, инстансный канал, ADR-089).
 *
 * Список идентичностей живёт не в сторе, а в панели профиля
 * (`ProfileSettings`): она грузит его своим запросом
 * (`GET /api/v2/me/identities`) и обновляет после **своих** действий. Стору
 * достаточно поднять `revision`, по нему панель перечитывает список без
 * перезагрузки страницы. Payload события сюда не нужен: он пуст по построению
 * (только вид мутации), потому что `provider`/`externalId` — персональные
 * данные человека, а канал доставляется ещё и администраторам.
 *
 * Баг, ради которого сигнал появился: «идентичность, привязанная
 * подтверждением кода в другой вкладке/на другом устройстве, и отвязка в
 * соседнем клиенте видны только после перезагрузки страницы».
 */
interface IdentitiesStore {
  /** Счётчик изменений идентичностей пользователя. */
  revision: number
  /** Идентичности изменились (привязка/отвязка) — поднять `revision`. */
  applyEvent: () => void
}

export const useIdentitiesStore = create<IdentitiesStore>((set) => ({
  revision: 0,
  applyEvent: () => set((s) => ({ revision: s.revision + 1 })),
}))
