import { create } from 'zustand'

/**
 * Счётчик изменений памяти инстанса (событие шины `memory.updated`, ADR-107,
 * инстансный канал).
 *
 * Три среза портала (статус, факты, индексы) живут не в сторе, а в компоненте
 * (`MemorySettings` грузит их своими запросами `GET /memory/status|facts|indexes`):
 * стору достаточно поднять `revision`, по нему раздел перечитывает данные без
 * перезагрузки страницы. Payload события сюда не нужен — в нём только область,
 * вид мутации и id записи (ни текста фактов, ни эмбеддингов в событии нет по
 * типу).
 *
 * Баг, ради которого сигнал появился: «факт, записанный агентом через плагин
 * памяти, и индекс, созданный другим админом, видны в разделе „Память“ только
 * после перезагрузки страницы».
 */
interface MemoryStore {
  /** Счётчик изменений памяти (факты и индексы). */
  revision: number
  /** Память изменилась (факт/индекс создан, изменён, удалён, пересобран) — поднять `revision`. */
  applyEvent: () => void
}

export const useMemoryStore = create<MemoryStore>((set) => ({
  revision: 0,
  applyEvent: () => set((s) => ({ revision: s.revision + 1 })),
}))
