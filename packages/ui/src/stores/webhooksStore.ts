import { create } from 'zustand'

/**
 * Счётчик изменений реестра webhooks инстанса (событие шины `webhooks.updated`,
 * инстансный канал, ADR-052 этап II).
 *
 * Список подписок живёт не в сторе, а в компоненте (`WebhooksSettings` грузит его
 * своим запросом `GET /api/v2/webhooks`): стору достаточно поднять `revision`, по
 * нему раздел перечитывает список без перезагрузки страницы. Payload события
 * сюда не нужен — в нём только id подписки и вид мутации (ни signing-секрета, ни
 * целевого URL с токеном получателя в событии нет по типу).
 *
 * Баг, ради которого сигнал появился: «подписка, созданная/изменённая/удалённая
 * во второй вкладке админки, видна только после перезагрузки страницы» — при
 * этом погашенная подписка продолжала выглядеть активной, а бейдж последней
 * доставки оставался прежним.
 */
interface WebhooksStore {
  /** Счётчик изменений реестра webhooks. */
  revision: number
  /** Реестр изменился (подписка создана/изменена/удалена/ротирована/погашена) — поднять `revision`. */
  applyEvent: () => void
}

export const useWebhooksStore = create<WebhooksStore>((set) => ({
  revision: 0,
  applyEvent: () => set((s) => ({ revision: s.revision + 1 })),
}))
