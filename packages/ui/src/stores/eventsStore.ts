import { create } from 'zustand'

/**
 * Счётчик изменений реестра приёма внешних событий (событие шины
 * `events.updated`, инстансный канал, ADR-089).
 *
 * Списки живут не в сторе, а в компонентах: раздел «События»
 * (`EventsAdminSettings`) грузит привязки своим запросом
 * (`GET /api/v2/events/bindings`), секция правил (`EventRoutesSection`) — свой
 * (`GET /api/v2/events/routes`), а карточка привязки (`EventBindingKeys`) —
 * метаданные ключей (`GET /api/v2/events/bindings/:id/keys`). Стору достаточно
 * поднять `revision`, по нему все три перечитывают свои списки без перезагрузки
 * страницы. Payload события сюда не нужен — в нём только вид мутации и id
 * привязки/правила (ни секрета ключа `synth_evt_…`, ни его хеша, ни id ключа в
 * событии нет по типу).
 *
 * Баг, ради которого сигнал появился: «привязка, ключ или правило, созданные
 * или удалённые во второй вкладке админки, видны только после перезагрузки
 * страницы» — при этом отозванный ключ продолжал выглядеть активным, а состав
 * правил маршрутизации оставался прежним.
 */
interface EventsStore {
  /** Счётчик изменений реестра приёма внешних событий. */
  revision: number
  /** Реестр изменился (привязка/ключ/правило) — поднять `revision`. */
  applyEvent: () => void
}

export const useEventsStore = create<EventsStore>((set) => ({
  revision: 0,
  applyEvent: () => set((s) => ({ revision: s.revision + 1 })),
}))
