import { create } from 'zustand'

/**
 * Счётчик изменений каталога пользователей инстанса (managed, событие шины
 * `users.updated`, инстансный канал).
 *
 * Список пользователей живёт не в сторе, а в компоненте (`UsersPanel` грузит его
 * своим запросом `GET /api/v2/users`): стору достаточно поднять `revision`, по
 * нему панель перечитывает список без перезагрузки страницы. Payload события
 * сюда не нужен — в нём только id и вид мутации (ни почты, ни ролей, ни заметок
 * в событии нет по типу).
 *
 * Баг, ради которого сигнал появился: «пользователь, созданный/отредактированный/
 * удалённый во второй вкладке админки, виден только после перезагрузки страницы».
 */
interface UsersStore {
  /** Счётчик изменений каталога пользователей. */
  revision: number
  /** Каталог изменился (пользователь создан/обновлён/удалён) — поднять `revision`. */
  applyEvent: () => void
}

export const useUsersStore = create<UsersStore>((set) => ({
  revision: 0,
  applyEvent: () => set((s) => ({ revision: s.revision + 1 })),
}))
