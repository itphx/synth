/** Нормализация поисковой строки: регистр, `ё → е`, внешние пробелы. */
export function normalizeSettingsQuery(value: string): string {
  return value.trim().toLowerCase().replace(/ё/g, 'е')
}

/** Разделители слов в подписях/синонимах: пробелы, пунктуация, слэши, скобки, дефисы. */
const WORD_SEPARATOR = /[\s,.;:!?()[\]{}/\\|«»"'`+-]+/
const RU_VOWEL = /[аеёиоуыэюя]/

/**
 * Совпадение слова с запросом по префиксу. Для русской морфологии допускаем
 * расхождение последней гласной: «тема» → «тема», «темы», «тему», «теме».
 */
function wordMatches(word: string, query: string): boolean {
  if (word.startsWith(query)) return true
  if (query.length > 3) {
    const head = query.slice(0, -1)
    const queryTail = query.at(-1) ?? ''
    const wordTail = word.charAt(head.length)
    if (
      RU_VOWEL.test(queryTail) &&
      RU_VOWEL.test(wordTail) &&
      word.startsWith(head)
    ) {
      return true
    }
  }
  return false
}

function matchesQuery(
  labelKey: string,
  keywords: string[] | undefined,
  query: string,
  t: (key: string) => string,
): boolean {
  const hasSpaces = /\s/.test(query)
  const values = [normalizeSettingsQuery(t(labelKey)), ...(keywords ?? []).map(normalizeSettingsQuery)]
  return values.some((value) => {
    if (!value) return false
    // Для многословного запроса сохраняем привычный подстрочный поиск.
    if (hasSpaces) return value.includes(query)
    // Иначе — по границам слов/префиксам, чтобы «тема» не находила «системе».
    if (value.startsWith(query)) return true
    return value.split(WORD_SEPARATOR).some((word) => word.length > 0 && wordMatches(word, query))
  })
}

/**
 * Поиск по каталогу настроек. Пустой запрос возвращает пустой результат: UI в
 * этом случае показывает сгруппированный сайдбар, а не «все совпадения».
 */
export function searchSettings(
  t: (key: string) => string,
  query: string,
): { categories: SettingsCategoryMeta[]; entries: SettingsCatalogEntry[] } {
  const normalized = normalizeSettingsQuery(query)
  if (!normalized) {
    return { categories: [], entries: [] }
  }

  return {
    categories: SETTINGS_CATEGORIES.filter((category) =>
      matchesQuery(category.labelKey, category.keywords, normalized, t),
    ),
    entries: SETTINGS_CATALOG.filter((entry) =>
      matchesQuery(entry.labelKey, entry.keywords, normalized, t),
    ),
  }
}
