// terminalScroll: затенение краёв терминала (PROP-132, Ф4б).
//
// Признаки те же, что у чата (`MessageList.handleScroll` → `data-scroll-shadow`):
// **два независимых** признака вместо одного «положения скролла»:
//   - сверху контент есть, когда вьюпорт уехал вниз от начала буфера;
//   - снизу контент есть, когда вьюпорт не в самом низу буфера.
//
// Модуль чистый (без React и без xterm): правило проверяется обычным тестом.

/** Признаки затенения краёв терминала. */
export interface TerminalScrollShadow {
  /** Сверху есть контент (вьюпорт прокручен вниз от начала буфера). */
  hasTop: boolean
  /** Снизу есть контент (вьюпорт не в конце буфера). */
  hasBottom: boolean
}

/**
 * Признаки затенения по положению вьюпорта в буфере xterm.
 *
 * `viewportY` — верхняя строка вьюпорта (сколько строк выше прокручено),
 * `baseY` — размер буфера прокрутки. На самом верху `viewportY === 0`,
 * на самом низу буфера `viewportY === baseY`; если вывод помещается целиком,
 * оба значения нулевые и затенения нет вовсе.
 */
export function scrollShadowState(viewportY: number, baseY: number): TerminalScrollShadow {
  return { hasTop: viewportY > 0, hasBottom: viewportY < baseY }
}
